def sequence_reads(start):
 # Original CA3 coefficient prefetch; CA6..CAF two sample kernel16 times,
 # N5=-4 and ordinary linear M5 restored fromY1A on selected AA8 mode1.
 r=start;reads=[dict(P='0xCA3',iteration=-1,address=r)];r+=1
 sites=[(0xca6,1),(0xca7,1),(0xca8,1),(0xca9,-4),(0xcaa,1),
        (0xcab,1),(0xcac,1),(0xcad,1),(0xcae,-4),(0xcaf,1)]
 for i in range(16):
  for pc,delta in sites:reads.append(dict(P=f'0x{pc:X}',iteration=i,address=r));r+=delta
 assert r==start+1 and {v['address'] for v in reads}==set(range(start,start+5))
 return reads

